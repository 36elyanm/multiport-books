// Embeds content/*.pdf into a plain JS module as base64, so /api/pdf never
// needs to read the filesystem at request time. Cloudflare Workers has no
// persistent disk, so a runtime fs.readFile would fail there even though it
// works fine on a normal Node host.
import { readFile, mkdir, writeFile } from "fs/promises";
import path from "path";

const CONTENT_DIR = path.join(process.cwd(), "content");
const OUT_DIR = path.join(process.cwd(), "lib", "generated");

const books = [{ slug: "the-weird-penguin", file: "the-weird-penguin.pdf" }];

async function main() {
  await mkdir(OUT_DIR, { recursive: true });

  for (const book of books) {
    const buffer = await readFile(path.join(CONTENT_DIR, book.file));
    const base64 = buffer.toString("base64");
    const outFile = path.join(OUT_DIR, `${book.slug}.ts`);
    await writeFile(
      outFile,
      `// Auto-generated by scripts/generate-pdf-asset.mjs — do not edit by hand.\nexport const base64 = ${JSON.stringify(base64)};\n`
    );
    console.log(`Generated ${path.relative(process.cwd(), outFile)} (${buffer.length} bytes source)`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
